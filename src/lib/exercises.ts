/** Calories burned: MET x 3.5 x kg / 200 per minute. */
export function burn(met: number, kg: number, minutes: number): number {
  return Math.round(((met * 3.5 * kg) / 200) * minutes)
}

/** Steps to kcal, roughly 0.0005 kcal per step per kg of body weight. */
export function stepKcal(steps: number, kg: number): number {
  return Math.round(steps * 0.0005 * kg)
}
